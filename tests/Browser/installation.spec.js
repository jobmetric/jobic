import { test, expect } from '@playwright/test';

// Run with the isolated installation-router.php and the separate config.
test('wizard saves its first step, resumes and displays connection errors on mobile', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/');
    await expect(page).toHaveURL(/\/installation$/);
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
    await expect(page.locator('.installation-language__choice')).toHaveCount(2);
    await expect(page.locator('[data-jump]')).toHaveCount(4);
    await expect(page.locator('form[data-step="1"] .reqv-summary progress')).toHaveAttribute('value', '21');
    await expect(page.locator('form[data-step="1"] .reqv-summary progress')).toHaveAttribute('max', '21');
    await expect(page.locator('form[data-step="1"] .reqv-summary')).toContainText('21 Passed');
    await expect(page.locator('.reqv-group').first()).not.toHaveAttribute('open');
    await page.locator('.reqv-group summary').first().click();
    await expect(page.locator('.reqv-group').first()).toHaveAttribute('open');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.setViewportSize({ width: 1438, height: 1093 });
    await page.locator('h2').filter({ hasText: 'Requirements' }).focus();
    await page.locator('h2').filter({ hasText: 'Requirements' }).evaluate(element => element.blur());
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/requirements-reference-en.png', animations: 'disabled' });
    await page.locator('[data-installation-help="documentation"]:visible').click();
    await expect(page.locator('[data-installation-dialog="documentation"]')).toBeVisible();
    await expect(page.locator('[data-installation-dialog="documentation"]')).toContainText('PHP 8.3');
    await page.keyboard.press('Escape');
    await page.locator('[data-installation-help="support"]:visible').click();
    await expect(page.locator('[data-installation-dialog="support"]')).toBeVisible();
    await page.locator('[data-installation-dialog="support"] button').click();
    await expect(page.locator('form[data-step="1"]')).toBeVisible();
    await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
    await page.screenshot({ path: 'test-results/requirements-desktop-en.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-theme-toggle]').click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await page.screenshot({ path: 'test-results/requirements-desktop-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-theme-toggle]').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.locator('[data-step-count]')).toHaveText('Step 1 of 4');
    await page.screenshot({ path: 'test-results/installation-language-english.png', fullPage: true, animations: 'disabled' });
    await page.evaluate(() => { window.installerDocument = document; });
    await page.locator('[data-language-form] button[value="fa"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'fa');
    await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
    expect(await page.evaluate(() => window.installerDocument === document)).toBe(true);
    await expect(page.locator('[data-step-count]')).toHaveText('مرحلهٔ ۱ از ۴');
    await expect(page.locator('form[data-step="1"]')).toBeVisible();
    const recheck = await page.locator('.installation-recheck').boundingBox();
    const next = await page.locator('form[data-step="1"] .installation-continue').boundingBox();
    expect(Math.abs(recheck.y - next.y)).toBeLessThan(3);
    expect(Math.abs(recheck.x - next.x)).toBeGreaterThan(50);
    await page.screenshot({ path: 'test-results/installation-language-persian.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 1438, height: 1093 });
    await page.screenshot({ path: 'test-results/requirements-desktop-fa.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.route('**/installation/steps', async (route) => {
        await new Promise((resolve) => setTimeout(resolve, 500));
        await route.continue();
    });
    await page.locator('form[data-step="1"] button[type="submit"]').click();
    await expect(page.locator('form[data-step="1"] button[type="submit"]')).toBeDisabled();
    await expect(page.locator('form[data-step="1"] button[type="submit"]')).toContainText('در حال');
    await expect(page.locator('form[data-step="2"]')).toBeVisible();
    await page.reload();
    await expect(page.locator('form[data-step="2"]')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    // Inspect the actual database form in both locales and both themes.
    await page.setViewportSize({ width: 1441, height: 1092 });
    await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
    await page.screenshot({ path: 'test-results/database-desktop-fa.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-theme-toggle]').click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await page.screenshot({ path: 'test-results/database-desktop-fa-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-language-form] button[value="en"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(page.locator('[data-theme-toggle]')).toHaveAttribute('aria-pressed', 'true');
    const inputPalette = await page.locator('#DB_HOST').evaluate(element => {
        const style = getComputedStyle(element);
        return { background: style.backgroundColor.match(/\d+/g).slice(0, 3).map(Number), text: style.color.match(/\d+/g).slice(0, 3).map(Number) };
    });
    expect(Math.max(...inputPalette.background)).toBeLessThan(100);
    expect(Math.min(...inputPalette.text)).toBeGreaterThan(180);
    await page.screenshot({ path: 'test-results/database-desktop-en-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('form[data-step="2"] .select2-selection').first().click();
    const dropdownBackground = await page.locator('.select2-dropdown').evaluate(element => getComputedStyle(element).backgroundColor.match(/\d+/g).slice(0, 3).map(Number));
    expect(Math.max(...dropdownBackground)).toBeLessThan(100);
    await page.screenshot({ path: 'test-results/database-dropdown-dark.png', fullPage: true, animations: 'disabled' });
    await page.keyboard.press('Escape');
    await page.locator('#DB_CONNECTION').selectOption('pgsql', { force: true });
    await expect(page.locator('#DB_PORT')).toHaveValue('5432');
    await page.locator('#DB_CONNECTION').selectOption('mariadb', { force: true });
    await expect(page.locator('#DB_PORT')).toHaveValue('3306');
    await page.locator('#DB_CONNECTION').selectOption('mysql', { force: true });
    await page.locator('[data-installation-help="database_documentation"]').click();
    await expect(page.locator('[data-installation-dialog="database_documentation"]')).toContainText('PostgreSQL');
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'test-results/database-mobile-dark.png', fullPage: true, animations: 'disabled' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.locator('[data-theme-toggle]').click();
    await page.setViewportSize({ width: 1441, height: 1092 });
    await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
    await page.screenshot({ path: 'test-results/database-desktop-en.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#DB_USERNAME').fill('browser-test');
    await page.locator('#DB_PASSWORD').fill('unsaved-password');
    await page.locator('[data-language-form] button[value="en"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(page.locator('form[data-step="2"]')).toBeVisible();
    await expect(page.locator('#DB_USERNAME')).toHaveValue('browser-test');
    await expect(page.locator('#DB_PASSWORD')).toHaveValue('unsaved-password');
    await page.getByRole('button', { name: 'Show password', exact: true }).first().click();
    await expect(page.locator('#DB_PASSWORD')).toHaveAttribute('type', 'text');
    await expect(page.locator('.installation-password-toggle').first()).toHaveAttribute('tabindex', '-1');
    await expect(page.locator('.password-eye-slash').first()).not.toHaveAttribute('hidden');
    await page.locator('#DB_PASSWORD').focus();
    await page.keyboard.press('Tab');
    await expect(page.locator('[data-test="database"]')).toBeFocused();
    await page.locator('[data-language-form] button[value="fa"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'fa');
    await expect(page.locator('#DB_PASSWORD')).toHaveValue('unsaved-password');
    await expect(page.locator('#DB_PASSWORD')).toHaveAttribute('type', 'password');
    await page.locator('#DB_PORT').fill('1');
    await expect(page.locator('form[data-step="2"] button[type=submit]')).toBeDisabled();
    await page.locator('[data-theme-toggle]').click();
    await page.locator('[data-test="database"]').click();
    await expect(page.locator('[data-ui-toast]')).toContainText('اتصال برقرار نشد');
    await expect(page.locator('[data-connection="database"]')).toHaveAttribute('data-state', 'error');
    await page.screenshot({ path: 'test-results/database-error-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-theme-toggle]').click();
    await expect(page.locator('[data-ui-toast]')).toHaveClass(/is-error/);
    await page.locator('[data-toast-dismiss]').click();
    await expect(page.locator('[data-ui-toast]')).toBeHidden();
    await expect(page.locator('form[data-step="2"]')).toBeVisible();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/installation-mobile.png', fullPage: true, animations: 'disabled' });

    // Continue in the owning browser through the remaining wizard steps.
    // Rendered server markup is real; deterministic responses exercise all UI states.
    await page.goto('/installation');
    const root = page.locator('[data-installation]');
    let step = Number(await root.getAttribute('data-step'));
    let task = 0;
    await page.route('**/installation/test/*', async (route) => {
        await new Promise(resolve => setTimeout(resolve, 700));
        await route.fulfill({ json: { ok: true, message: 'اتصال با موفقیت برقرار شد.' } });
    });
    await page.route('**/installation/steps', async (route) => {
        step = Number(route.request().postDataJSON().step);
        await route.fulfill({ json: { ok: true, message: 'ذخیره شد', data: { step } } });
    });
    await page.route('**/installation/start', (route) => route.fulfill({ json: { ok: true, data: { task: 0, percent: 0 } } }));
    await page.route('**/installation/next', async (route) => {
        await new Promise(resolve => setTimeout(resolve, 200));
        task++;
        await route.fulfill({ json: { ok: true, data: { task, percent: Math.floor(task / 6 * 100), completed: task === 6 } } });
    });
    if (step === 1) await page.locator('form[data-step="1"] button[type="submit"]').click();
    await page.locator('[data-test="database"]').click();
    await expect(page.locator('[data-connection="database"]')).toHaveAttribute('data-state', 'pending');
    await expect(page.locator('[data-test="database"]')).toBeDisabled();
    await expect(page.locator('[data-test="database"]')).toContainText('در حال');
    await expect(page.locator('[data-connection="database"]')).toHaveAttribute('data-state', 'success');
    await expect(page.locator('form[data-step="2"] button[type=submit]')).toBeEnabled();
    await page.locator('#DB_HOST').fill('changed.example.test');
    await expect(page.locator('form[data-step="2"] button[type=submit]')).toBeDisabled();
    await page.locator('[data-test="database"]').click();
    await expect(page.locator('form[data-step="2"] button[type=submit]')).toBeEnabled();
    await page.locator('form[data-step="2"] button[type="submit"]').click();
    await expect(page.locator('form[data-step="5"]')).toBeVisible();
    await page.locator('[data-theme-toggle]').click();
    await page.setViewportSize({ width: 1441, height: 1092 });
    await page.screenshot({ path: 'test-results/administrator-desktop-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-language-form] button[value="en"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await page.locator('[data-theme-toggle]').click();
    await page.screenshot({ path: 'test-results/administrator-reference-en.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'test-results/administrator-mobile-en.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 1441, height: 1092 });
    await page.locator('#APP_URL').fill('https://example.test');
    await page.locator('#ADMIN_NAME').fill('Owner');
    await page.locator('#ADMIN_EMAIL').fill('owner@example.test');
    await page.locator('#ADMIN_PASSWORD').fill('long-browser-password');
    await page.locator('#ADMIN_PASSWORD_confirmation').fill('long-browser-password');
    await page.locator('form[data-step="5"] button[type="submit"]').click();
    await expect(page.locator('[data-task-status]').first()).toHaveText('Pending');
    await page.screenshot({ path: 'test-results/install-reference-en.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-language-form] button[value="fa"]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'fa');
    await page.locator('[data-theme-toggle]').click();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'test-results/install-mobile-fa-dark.png', fullPage: true, animations: 'disabled' });
    await page.locator('[data-run]').click();
    await expect(page.locator('[data-run-progress]')).toHaveAttribute('value', '100');
    await expect(page.locator('[data-login]')).toBeVisible();
    await expect(page.locator('[data-task].is-passed .installation-task-mark')).toHaveCount(6);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/installation-completed.png', fullPage: true, animations: 'disabled' });
});
